/**
 * LOCAL console.
 *
 * A deliberately small chat surface for operating Paperclip itself. It is not a
 * task surface: it never creates issues, agents, or artifacts, and the model is
 * instructed not to produce deliverables unless the operator asks for one
 * through the normal task flow. Commands are handled server-side against the
 * real services, so nothing here re-implements control-plane behaviour.
 *
 * POST /api/companies/:companyId/local-chat
 *   { message } → { reply, source, artifactsUrl, provider? }
 *
 * @module server/routes/local-chat
 */

import { Router } from "express";
import type { Db } from "@paperclipai/db";
import { assertBoardOrgAccess, assertCompanyAccess } from "./authz.js";
import { logger } from "../middleware/logger.js";
import { createProviderDiscoveryService } from "../services/provider-discovery/index.js";

const SYSTEM_PROMPT = [
  "You are Paperclip's local operator console.",
  "Answer questions about the instance, the configured models, agents and artifacts.",
  "Do not assume the user wants a file, task, or artifact. Never claim to have created one.",
  "If the user wants a deliverable, tell them to ask for it explicitly in a task.",
  "Be concise and technical. Never reveal credentials or environment variable values.",
].join(" ");

interface LocalChatReply {
  reply: string;
  source: "command" | "model" | "unavailable";
  artifactsUrl: string;
  provider?: string;
}

export interface LocalChatRouteOptions {
  db: Db;
  deployment: {
    bindHost: string;
    port: number;
    deploymentMode?: string;
    deploymentExposure?: string;
  };
}

function resolveModelEndpoint(env: NodeJS.ProcessEnv): {
  baseUrl: string;
  apiKey: string;
  model: string;
  provider: string;
} | null {
  if (env.OPENROUTER_API_KEY?.trim()) {
    return {
      baseUrl: (env.OPENROUTER_BASE_URL ?? "https://openrouter.ai/api/v1").replace(/\/+$/, ""),
      apiKey: env.OPENROUTER_API_KEY.trim(),
      model: env.PAPERCLIP_LOCAL_CHAT_MODEL ?? "openai/gpt-4o-mini",
      provider: "openrouter",
    };
  }
  if (env.OPENAI_API_KEY?.trim()) {
    return {
      baseUrl: (env.OPENAI_BASE_URL ?? "https://api.openai.com/v1").replace(/\/+$/, ""),
      apiKey: env.OPENAI_API_KEY.trim(),
      model: env.PAPERCLIP_LOCAL_CHAT_MODEL ?? "gpt-4o-mini",
      provider: "openai",
    };
  }
  return null;
}

async function askModel(
  message: string,
  signal: AbortSignal,
): Promise<{ reply: string; provider: string } | null> {
  const target = resolveModelEndpoint(process.env);
  if (!target) return null;
  try {
    const response = await fetch(`${target.baseUrl}/chat/completions`, {
      method: "POST",
      headers: {
        "content-type": "application/json",
        authorization: `Bearer ${target.apiKey}`,
      },
      body: JSON.stringify({
        model: target.model,
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          { role: "user", content: message },
        ],
        max_tokens: 1200,
      }),
      signal,
    });
    if (!response.ok) {
      logger.warn({ status: response.status, provider: target.provider }, "local chat provider refused the request");
      return null;
    }
    const body = (await response.json()) as {
      choices?: Array<{ message?: { content?: string } }>;
    };
    const reply = body.choices?.[0]?.message?.content?.trim();
    return reply ? { reply, provider: target.provider } : null;
  } catch (error) {
    logger.warn({ err: (error as Error).message }, "local chat provider call failed");
    return null;
  }
}

export function localChatRoutes(options: LocalChatRouteOptions) {
  const router = Router();

  router.post("/companies/:companyId/local-chat", async (req, res) => {
    const companyId = req.params.companyId as string;
    assertBoardOrgAccess(req);
    assertCompanyAccess(req, companyId);

    const raw = typeof req.body?.message === "string" ? req.body.message : "";
    const message = raw.trim();
    if (!message) {
      res.status(422).json({ error: "message is required" });
      return;
    }

    const artifactsUrl = `/${companyId}/artifacts`;
    const command = message.toLowerCase();

    if (command === "/help" || command === "help") {
      const reply = [
        "LOCAL console commands:",
        "  /providers — scan this instance for configured providers and reachable endpoints",
        "  /artifacts — open the artifact browser",
        "  /help      — this list",
        "Anything else is sent to the configured model as a plain chat turn. No task or artifact is created unless you ask for one in a task.",
      ].join("\n");
      res.json({ reply, source: "command", artifactsUrl } satisfies LocalChatReply);
      return;
    }

    if (command === "/artifacts") {
      res.json({
        reply: "Artifacts generated by tasks are listed in the artifact browser.",
        source: "command",
        artifactsUrl,
      } satisfies LocalChatReply);
      return;
    }

    if (command === "/providers") {
      const service = createProviderDiscoveryService({ deployment: options.deployment });
      const started = service.start(companyId);
      const deadline = Date.now() + 15_000;
      let snapshot = started;
      while (snapshot.status === "running" && Date.now() < deadline) {
        await new Promise((resolve) => setTimeout(resolve, 150));
        snapshot = service.get(companyId, started.id) ?? snapshot;
      }
      const lines = snapshot.findings.length
        ? snapshot.findings.map(
            (finding) =>
              `• ${finding.label} — ${finding.status.replace(/_/g, " ")}${finding.endpoint ? ` @ ${finding.endpoint}` : ""}${finding.credential === "present" ? " (credential present)" : ""}`,
          )
        : ["No providers found."];
      const notes = snapshot.limitations.length
        ? ["", ...snapshot.limitations.map((note) => `note: ${note}`)]
        : [];
      res.json({
        reply: [`Provider inventory (${snapshot.status}):`, ...lines, ...notes].join("\n"),
        source: "command",
        artifactsUrl,
      } satisfies LocalChatReply);
      return;
    }

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 60_000);
    try {
      const answer = await askModel(message, controller.signal);
      if (!answer) {
        res.json({
          reply:
            "No model is reachable from this console yet. Set OPENROUTER_API_KEY or OPENAI_API_KEY in the server environment (or configure a provider in agent setup), then retry. Provider scanning is available with /providers.",
          source: "unavailable",
          artifactsUrl,
        } satisfies LocalChatReply);
        return;
      }
      res.json({
        reply: answer.reply,
        source: "model",
        provider: answer.provider,
        artifactsUrl,
      } satisfies LocalChatReply);
    } finally {
      clearTimeout(timer);
    }
  });

  return router;
}
